#输入三个整数，判断它们是构成等边三角形还是等腰三角形还是普通三角形，还是不能构#成三角形，给出相应的输出。
#分析：三角形的基本条件，每条边都>0且任意两边之和大于第三边
a,b,c=input().split(',')                    # 接收三边数据
a,b,c=int(a),int(b),int(c)
# #如果三边满足a>0 and b>0 and c>0 and a+b>c and a+c>b and b+c>a:
if (a>0 and b>0 and c>0) and (a+b>c or a+c>b or b+c>a):
#    如果三边相等:
#        打印"等边三角形"
#    否则，如果有任意两边相等:
#        打印"等腰三角形"
#    如果三边都不相等，
#        输出普通三角形
    if a==b==c:
        print("等边三角形")
    elif a==b or a==c or b==c:
        print("等腰三角形")
    else:
        print("普通三角形")
#        打印"等边三角形"
#    否则，如果有任意两边相等:
#        打印"等腰三角形"
#    如果三边都不相等，
#        输出普通三角形
#如果不满足，
#    提示"输入错误，不能构成三角形"
else:
    print("输入错误，不能构成三角形")
        
